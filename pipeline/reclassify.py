def classify(title):
    for sub, cat in OVERRIDES.items():
        if sub in title:
            return cat
    low = title.lower()
    for name, rx in RULES:
        if rx.search(low):
            return name
    return "Стратегия-и-медиапланирование"

def build_rows():
    rows = []
    for path in glob.glob(os.path.join(OUT, '*', '*.txt')):
        h = read_header(path)
        title = h.get('Название', '')
        url = h.get('Источник (YouTube)', '')
        m = re.search(r'watch\?v=([\w-]+)(?:&t=(\d+))?', url)
        vid = m.group(1) if m else ''
        start_t = m.group(2) if (m and m.group(2)) else ''
        old = os.path.basename(os.path.dirname(path))
        new = classify(title)
        rows.append((path, vid, start_t, old, new, title))
    return rows


def main():
    rows = build_rows()
    # write map
    with open(os.path.join(WORK, 'reclass_map.tsv'), 'w', encoding='utf-8') as o:
        for path, vid, start_t, old, new, title in rows:
            o.write(f"{path}\t{vid}\t{start_t}\t{old}\t{new}\t{title}\n")

    # distribution
    dist = collections.Counter(r[4] for r in rows)
    print(f"TOTAL {len(rows)} files -> {len(dist)} categories\n")
    for cat, n in sorted(dist.items(), key=lambda x: -x[1]):
        print(f"  {n:>3}  {cat}")

    # full grouped listing
    by = collections.defaultdict(list)
    for path, vid, start_t, old, new, title in rows:
        by[new].append((old, title))
    print("\n" + "=" * 70)
    for cat in sorted(by, key=lambda c: -len(by[c])):
        print(f"\n########## {cat} ({len(by[cat])}) ##########")
        for old, title in sorted(by[cat]):
            print(f"  [{old[:22]:22}] {title[:88]}")


if __name__ == '__main__':
    main()
