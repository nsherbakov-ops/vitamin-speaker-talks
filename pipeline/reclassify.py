def read_header(path):
    h = {}
    with open(path, encoding='utf-8') as f:
        for _ in range(20):
            line = f.readline()
            if not line or line.startswith('='):
                break
            if ':' in line:
                k, v = line.split(':', 1)
                h[k.strip()] = v.strip()
    return h

